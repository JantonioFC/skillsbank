def translate_with_dict(text):
    # 1. Aplicar patrones Regex primero (frases completas)
    for pattern, replacement in TRANSLATION_PATTERNS:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    
    # 2. Traducir terminos del diccionario (ordenados por longitud para evitar solapamientos)
    sorted_terms = sorted(COMMON_TERMS.keys(), key=len, reverse=True)
    
    for en in sorted_terms:
        # Usar limites de palabra para evitar reemplazos parciales incorrectos
        es = COMMON_TERMS[en]
        # Regex escapado para el término en inglés
        text = re.sub(r'\b' + re.escape(en) + r'\b', es, text, flags=re.IGNORECASE)
            
    return text

def get_skill_info(skill_dir):
    skill_file = os.path.join(skill_dir, "SKILL.md")
    if not os.path.exists(skill_file):
        return None, None
        
    try:
        with open(skill_file, "r", encoding="utf-8", errors="ignore") as f:
            content = f.read()
    except:
        return None, None
    
    name = os.path.basename(skill_dir)
    description = ""
    
    fm_match = re.search(r'^---(.*?)---', content, re.DOTALL)
    if fm_match:
        fm = fm_match.group(1)
        name_match = re.search(r'name:\s*(.*)', fm)
        if name_match: name = name_match.group(1).strip().strip('"')
        desc_match = re.search(r'description:\s*"(.*?)"', fm)
        if not desc_match: desc_match = re.search(r'description:\s*(.*)', fm)
        if desc_match: description = desc_match.group(1).strip().strip('"')
        
    return name, description

def main():
    translations = {}
    if os.path.exists(TRANSLATIONS_FILE):
        try:
            with open(TRANSLATIONS_FILE, "r", encoding="utf-8") as f:
                translations = json.load(f)
        except: pass
    
    count = 0
    for item in os.listdir(SKILLS_DIR):
        path = os.path.join(SKILLS_DIR, item)
        if not os.path.isdir(path): continue
        
        name, description = get_skill_info(path)
        if not name: continue
        
        # Si ya existe traducción manual, conservar
        if name in translations and not translations[name].get("auto_generated", True):
            continue
            
        # Generar traducción
        es_description = translate_with_dict(description)
        
        # Limpieza básica
        es_description = es_description.replace("Triggers:", "Activadores:")
        es_description = es_description.replace("Use for:", "Usar para:")
        
        translations[name] = {
            "description": es_description,
            "auto_generated": True
        }
        count += 1

    with open(TRANSLATIONS_FILE, "w", encoding="utf-8") as f:
        json.dump(translations, f, indent=2, ensure_ascii=False)
        
    print(f"Generated translations for {count} skills into {TRANSLATIONS_FILE}")

if __name__ == "__main__":
    main()
